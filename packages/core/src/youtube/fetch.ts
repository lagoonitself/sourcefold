// Saves a YouTube video's transcript. The method is jdepoix/youtube-transcript-api's (MIT):
// read the InnerTube API key from the watch page, ask the InnerTube player endpoint as the
// Android app (which still returns caption addresses that work without a proof-of-origin token),
// then fetch the chosen track's timedtext file. No API key of the user's own is needed.
//
// YouTube blocks most cloud servers, so this runs in the desktop app and the extension, each
// passing its own `SourceFetch`.

import type { SourceCapture, SourceExtractResult } from "../capture-types";
import { SourceError, type SourceFetch, type SourceFetchResponse } from "../source-fetch";
import { parseYouTubeLink, youTubeVideoUrl } from "../source-links";
import { formatTimestamp, youTubeBodyMarkdown } from "./markdown";
import { parseTimedText } from "./timedtext";
import {
  TRANSCRIPT_LANGUAGE,
  chooseCaptionTrack,
  isAutoGenerated,
  timedTextUrl,
  type CaptionTrack,
} from "./tracks";

export const YOUTUBE_NO_CAPTIONS_REASON = "No captions on this video";

export const YOUTUBE_NO_ENGLISH_MESSAGE =
  "This video has no English captions, and YouTube wouldn't translate them just now. Try again later.";

/** The InnerTube client youtube-transcript-api uses, asking for English names. */
export const INNERTUBE_CONTEXT = {
  client: { clientName: "ANDROID", clientVersion: "20.10.38", hl: "en" },
} as const;

export interface YouTubeFetchOptions {
  fetch: SourceFetch;
  signal?: AbortSignal;
}

/** The parts of an InnerTube player response Sourcefold reads. */
export interface YouTubePlayerResponse {
  playabilityStatus?: { status?: string; reason?: string };
  videoDetails?: {
    videoId?: string;
    title?: string;
    author?: string;
    channelId?: string;
    lengthSeconds?: string;
    shortDescription?: string;
  };
  captions?: {
    playerCaptionsTracklistRenderer?: {
      captionTracks?: CaptionTrack[];
      /** One per audio language; `captionTrackIndices[0]` is that audio's own captions. */
      audioTracks?: { captionTrackIndices?: number[]; defaultCaptionTrackIndex?: number }[];
      defaultAudioTrackIndex?: number;
    };
  };
  microformat?: {
    playerMicroformatRenderer?: {
      publishDate?: string;
      uploadDate?: string;
      title?: { simpleText?: string };
    };
  };
}

export const YOUTUBE_BLOCKED_MESSAGE =
  "YouTube is limiting requests from this connection. Wait a few minutes and try again.";

/** True for YouTube's rate limit or bot check, which clears after a pause. */
export function isYouTubeRateLimit(error: unknown): boolean {
  return (
    error instanceof SourceError &&
    error.code === "blocked" &&
    error.message === YOUTUBE_BLOCKED_MESSAGE
  );
}

/**
 * Reads the JSON object assigned after `marker` in a page script (`var ytInitialPlayerResponse = {…};`),
 * matching braces outside strings. Null when it isn't there or doesn't parse.
 */
export function extractJsonAfter(html: string, marker: string): unknown {
  const at = html.indexOf(marker);
  if (at === -1) return null;
  const start = html.indexOf("{", at + marker.length);
  if (start === -1) return null;

  let depth = 0;
  let inString = false;
  for (let i = start; i < html.length; i++) {
    const char = html[i];
    if (inString) {
      if (char === "\\") i++;
      else if (char === '"') inString = false;
    } else if (char === '"') {
      inString = true;
    } else if (char === "{") {
      depth++;
    } else if (char === "}") {
      depth--;
      if (depth === 0) {
        try {
          return JSON.parse(html.slice(start, i + 1));
        } catch {
          return null;
        }
      }
    }
  }
  return null;
}

export function checkYouTubeStatus(response: SourceFetchResponse, what: string): void {
  if (response.status === 429) throw new SourceError("blocked", YOUTUBE_BLOCKED_MESSAGE);
  if (response.status === 404) {
    throw new SourceError(
      "not_found",
      what === "page"
        ? "YouTube couldn't find this page. Check the link."
        : "This video isn't available. It may be private or deleted.",
    );
  }
  if (response.status < 200 || response.status >= 300) {
    throw new SourceError(
      response.status === 403 ? "blocked" : "fetch_failed",
      `YouTube didn't send the ${what} (error ${response.status}). Try again in a minute.`,
    );
  }
}

const CONSENT_FORM = 'action="https://consent.youtube.com/s"';
const CONSENT_MESSAGE =
  "YouTube asked for cookie consent. Open YouTube in your browser once, then try again.";

/**
 * Fetches a youtube.com page as HTML. EU visitors get a cookie consent page first; accepting it
 * is a `CONSENT` cookie with the form's value, which later requests must send too.
 */
export async function fetchYouTubePage(
  url: string,
  options: YouTubeFetchOptions,
  what = "page",
): Promise<{ html: string; cookie?: string }> {
  const headers = { Accept: "text/html", "Accept-Language": "en-US,en;q=0.9" };
  let response = await options.fetch({ url, headers, signal: options.signal });
  checkYouTubeStatus(response, what);
  let html = response.text;
  let cookie: string | undefined;

  if (html.includes(CONSENT_FORM)) {
    const value = html.match(/name="v" value="(.*?)"/)?.[1];
    if (!value) throw new SourceError("blocked", CONSENT_MESSAGE);
    cookie = `CONSENT=YES+${value}`;
    response = await options.fetch({
      url,
      headers: { ...headers, Cookie: cookie },
      signal: options.signal,
    });
    checkYouTubeStatus(response, what);
    html = response.text;
    if (html.includes(CONSENT_FORM)) throw new SourceError("blocked", CONSENT_MESSAGE);
  }

  if (html.includes('class="g-recaptcha"'))
    throw new SourceError("blocked", YOUTUBE_BLOCKED_MESSAGE);
  return { html, cookie };
}

function assertPlayable(player: YouTubePlayerResponse): void {
  const status = player.playabilityStatus?.status;
  if (!status || status === "OK") return;
  const reason = player.playabilityStatus?.reason ?? "";

  if (status === "LOGIN_REQUIRED") {
    if (/not a bot/i.test(reason)) throw new SourceError("blocked", YOUTUBE_BLOCKED_MESSAGE);
    if (/age|inappropriate/i.test(reason)) {
      throw new SourceError(
        "blocked",
        "This video is age-restricted, so YouTube doesn't share its captions without signing in.",
      );
    }
    throw new SourceError("blocked", "This video is private or needs a sign-in to watch.");
  }
  if (status === "ERROR") {
    throw new SourceError("not_found", "This video isn't available. It may be private or deleted.");
  }
  throw new SourceError(
    "not_found",
    reason ? `YouTube can't play this video: ${reason}` : "YouTube can't play this video.",
  );
}

function publishedDate(watchPlayer: YouTubePlayerResponse | null): string | null {
  const micro = watchPlayer?.microformat?.playerMicroformatRenderer;
  const raw = micro?.publishDate ?? micro?.uploadDate;
  return raw && /^\d{4}-\d{2}-\d{2}/.test(raw) ? raw.slice(0, 10) : null;
}

function languageCode(code: string): string {
  return code.replace(/_/g, "-");
}

/**
 * Fetches a video's transcript and builds its capture. A video without captions comes back as
 * `unavailable` with the reason "No captions on this video". Errors YouTube explains (private,
 * deleted, age-restricted, rate limits) are thrown as a `SourceError`.
 */
export async function fetchYouTubeCapture(
  url: string,
  options: YouTubeFetchOptions,
): Promise<SourceExtractResult> {
  const link = parseYouTubeLink(url);
  if (!link) throw new SourceError("invalid_url", "That isn't a YouTube video link.");
  if (link.type !== "video") {
    throw new SourceError(
      "invalid_url",
      "That's a YouTube playlist or channel, not a single video.",
    );
  }
  const videoId = link.videoId;
  const canonical = youTubeVideoUrl(videoId);

  const { html, cookie } = await fetchYouTubePage(canonical, options, "video page");
  const apiKey = html.match(/"INNERTUBE_API_KEY":\s*"([a-zA-Z0-9_-]+)"/)?.[1];
  if (!apiKey) {
    throw new SourceError("parse_failed", "Couldn't read the YouTube page. Try again in a minute.");
  }
  const watchPlayer = extractJsonAfter(
    html,
    "var ytInitialPlayerResponse = ",
  ) as YouTubePlayerResponse | null;

  const playerResponse = await options.fetch({
    url: `https://www.youtube.com/youtubei/v1/player?key=${apiKey}`,
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "Accept-Language": "en-US,en;q=0.9",
      ...(cookie ? { Cookie: cookie } : {}),
    },
    body: JSON.stringify({ context: INNERTUBE_CONTEXT, videoId }),
    signal: options.signal,
  });
  checkYouTubeStatus(playerResponse, "video details");
  let player: YouTubePlayerResponse;
  try {
    player = JSON.parse(playerResponse.text) as YouTubePlayerResponse;
  } catch {
    throw new SourceError("parse_failed", "Couldn't read YouTube's reply. Try again in a minute.");
  }
  assertPlayable(player);

  const details = player.videoDetails ?? watchPlayer?.videoDetails ?? {};
  const title =
    details.title?.trim() ||
    watchPlayer?.microformat?.playerMicroformatRenderer?.title?.simpleText?.trim() ||
    `YouTube video ${videoId}`;

  const tracklist = player.captions?.playerCaptionsTracklistRenderer;
  const audio = tracklist?.audioTracks?.[tracklist?.defaultAudioTrackIndex ?? 0];
  const choice = chooseCaptionTrack(
    tracklist?.captionTracks ?? [],
    audio?.captionTrackIndices?.[0] ?? audio?.defaultCaptionTrackIndex,
  );
  if (!choice) {
    return {
      status: "unavailable",
      kind: "youtube",
      url: canonical,
      title,
      reason: YOUTUBE_NO_CAPTIONS_REASON,
    };
  }
  const { track, translate } = choice;
  if (track.baseUrl.includes("&exp=xpe")) {
    throw new SourceError(
      "blocked",
      "YouTube wants extra verification for these captions. Try the Sourcefold extension while watching the video.",
    );
  }

  const captionResponse = await options.fetch({
    url: timedTextUrl(track, translate ? TRANSCRIPT_LANGUAGE : undefined),
    headers: { "Accept-Language": "en-US,en;q=0.9", ...(cookie ? { Cookie: cookie } : {}) },
    signal: options.signal,
  });
  // YouTube refuses most translation requests (429) while untranslated tracks still come through,
  // so this isn't the connection-wide rate limit.
  if (translate && captionResponse.status === 429) {
    throw new SourceError("blocked", YOUTUBE_NO_ENGLISH_MESSAGE);
  }
  checkYouTubeStatus(captionResponse, "captions");
  const segments = parseTimedText(captionResponse.text);
  if (segments.length === 0) {
    throw new SourceError(
      "parse_failed",
      "YouTube sent empty captions for this video. Try again in a minute.",
    );
  }

  const lengthSeconds = Number(details.lengthSeconds);
  const capture: SourceCapture = {
    url: canonical,
    title,
    meta: {
      channel: details.author?.trim() || null,
      channel_url: details.channelId
        ? `https://www.youtube.com/channel/${details.channelId}`
        : null,
      published: publishedDate(watchPlayer),
      duration:
        Number.isFinite(lengthSeconds) && lengthSeconds > 0 ? formatTimestamp(lengthSeconds) : null,
      language: translate ? TRANSCRIPT_LANGUAGE : languageCode(track.languageCode),
      captions: translate ? "translated" : isAutoGenerated(track) ? "auto-generated" : "manual",
    },
    markdown: youTubeBodyMarkdown(videoId, segments, details.shortDescription),
  };
  return { status: "ok", kind: "youtube", capture };
}
